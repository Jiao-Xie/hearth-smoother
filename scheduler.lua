-- Only schedule notifications. The captured engine callback dispatcher remains intact.
local M = {}
local config = { enabled = true, batch_size = 64, max_delay_seconds = 0.4 }
local state = {
   applied = false, pending = {}, queue = {}, count = 0,
   queued_total = 0, processed_total = 0, coalesced_total = 0,
   peak_pending = 0, deferred_total = 0, bypass_total = 0,
   overdue_total = 0, overflow_drains = 0, max_batch = 0,
   loops = 0, empty_loops = 0, empty_fast_calls = 0,
   empty_dispatch_fast_path = false, error_count = 0, last_log = 0
}
local MAX_PENDING = 2048
local original, wrapper, service
local trusted_callbacks, trusted_registration
local EXPECTED_AI_SOURCE = '@stonehearth/services/server/ai/ai_service.lua'
local log = radiant.log.create_logger('hearth_smoother')

local function now()
   return radiant.get_realtime()
end

local function write_status(reason)
   log:write(0, '%s enabled=%s applied=%s pending=%d queued=%d processed=%d peak=%d deferred=%d bypass=%d overdue=%d overflow=%d max_batch=%d errors=%d empty_loops=%d',
      reason, tostring(config.enabled), tostring(state.applied), state.count,
      state.queued_total, state.processed_total, state.peak_pending,
      state.deferred_total, state.bypass_total, state.overdue_total,
      state.overflow_drains, state.max_batch, state.error_count, state.empty_loops)
end

local function maybe_log(time)
   if time - state.last_log >= 30 then
      state.last_log = time
      write_status('aggregate')
   end
end

local function has_stock_source(fn)
   if type(fn) ~= 'function' or not debug or type(debug.getinfo) ~= 'function' then return false end
   local ok, info = pcall(debug.getinfo, fn, 'S')
   return ok and type(info) == 'table' and info.source == EXPECTED_AI_SOURCE
end

local function plain_table(value)
   return type(value) == 'table' and getmetatable(value) == nil
end

local function plain_entries(map)
   if not plain_table(map) then return false end
   for _, entry in pairs(map) do
      if not plain_table(entry) then return false end
   end
   return true
end

local function owns_empty_fast_path(ai)
   return state.applied and state.empty_dispatch_fast_path
      and ai._call_reconsider_callbacks == wrapper
      and ai.on_reconsider_entity == trusted_registration
      and ai._reconsider_callbacks == trusted_callbacks
      and plain_table(ai._reconsider_callbacks)
      and plain_table(ai._reconsidered_entities)
end

local function explicit_priority(msg)
   if type(msg) ~= 'table' then return true end
   if msg.destroyed or msg.destroy or msg.player_id_changed then return true end
   local reason = type(msg.reason) == 'string' and string.lower(msg.reason) or ''
   return string.find(reason, 'destroy', 1, true) ~= nil
      or string.find(reason, 'player_id', 1, true) ~= nil
end

local function priority_and_owner(msg, previous_owner)
   if explicit_priority(msg) then return true end
   local entity = msg.entity
   if not entity or not entity:is_valid() then return true end
   if entity:get_component('stonehearth:ai') then return true end
   local owner = entity:get_player_id()
   return previous_owner ~= nil and owner ~= previous_owner, owner
end

local function merge_back()
   -- Engine map wins: it can contain a newer notification generated by a callback.
   local merged = {}
   for id, entry in pairs(state.pending) do merged[id] = entry.msg end
   for id, msg in pairs(state.active_batch or {}) do merged[id] = msg end
   local incoming = service._reconsidered_entities
   if type(incoming) == 'table' then
      for id, msg in pairs(incoming) do merged[id] = msg end
   end
   service._reconsidered_entities = merged
   state.pending, state.queue, state.count, state.active_batch = {}, {}, 0, nil
end

local function prepare_batch(ai)
   local time = now()
   local incoming = ai._reconsidered_entities
   assert(type(incoming) == 'table', 'AI notification map changed type')
   if state.count == 0 and next(incoming) == nil then
      -- Keep the exact incoming map and the original empty dispatcher/C++ call.
      -- Avoid our two temporary queue/batch tables when there is no work.
      state.loops = state.loops + 1
      state.empty_loops = state.empty_loops + 1
      maybe_log(time)
      return true
   end
   state.active_batch = {}
   for id, msg in pairs(incoming) do
      local entry = state.pending[id]
      if entry then
         entry.msg = msg -- Coalesce to the latest observed message, keep original age.
         state.coalesced_total = state.coalesced_total + 1
      else
         local _, owner = priority_and_owner(msg)
         entry = { id = id, msg = msg, time = time, owner = owner }
         state.pending[id] = entry
         state.queue[#state.queue + 1] = entry
         state.count = state.count + 1
         state.queued_total = state.queued_total + 1
      end
   end
   state.peak_pending = math.max(state.peak_pending, state.count)
   local overflow = state.count > MAX_PENDING
   if overflow then state.overflow_drains = state.overflow_drains + 1 end
   local batch, remaining = state.active_batch, {}
   local ordinary, processed = 0, 0
   for _, entry in ipairs(state.queue) do
      local priority = priority_and_owner(entry.msg, entry.owner)
      local overdue = time - entry.time >= config.max_delay_seconds
      if overflow or priority or overdue or ordinary < config.batch_size then
         batch[entry.id] = entry.msg
         state.pending[entry.id] = nil
         state.count = state.count - 1
         processed = processed + 1
         if priority then
            state.bypass_total = state.bypass_total + 1
         elseif overdue then
            state.overdue_total = state.overdue_total + 1
         else
            ordinary = ordinary + 1
         end
      else
         remaining[#remaining + 1] = entry
      end
   end
   state.queue = remaining
   state.deferred_total = state.deferred_total + state.count
   state.processed_total = state.processed_total + processed
   state.max_batch = math.max(state.max_batch, processed)
   state.loops = state.loops + 1
   -- Do all wrapper work before dispatch: errors in engine callbacks retain engine semantics.
   maybe_log(time)
   ai._reconsidered_entities = batch
end

function M.status()
   local result = {
      enabled = config.enabled, applied = state.applied,
      batch_size = config.batch_size, max_delay_seconds = config.max_delay_seconds,
      overflow_threshold = MAX_PENDING, pending = state.count,
      last_error = state.last_error, oldest_pending_age_seconds = 0
   }
   for _, key in ipairs({ 'queued_total', 'processed_total', 'coalesced_total',
      'peak_pending', 'deferred_total', 'bypass_total', 'overdue_total',
      'overflow_drains', 'max_batch', 'loops', 'empty_loops', 'error_count' }) do
      result[key] = state[key]
   end
   result.empty_dispatch_fast_path = service ~= nil and owns_empty_fast_path(service) or false
   result.empty_fast_calls = state.empty_fast_calls
   if state.queue[1] then
      local ok, time = pcall(now)
      if ok then result.oldest_pending_age_seconds = math.max(0, time - state.queue[1].time) end
   end
   result.grid_trace = hearth_smoother_grid_trace and hearth_smoother_grid_trace.status()
      or { applied = false, active = false }
   result.death_guard = hearth_smoother_death_guard and hearth_smoother_death_guard.status()
      or { applied = false, active = false }
   result.event_guard = hearth_smoother_event_guard and hearth_smoother_event_guard.status()
      or { applied = false, active = false }
   result.component_data_cache = hearth_smoother_component_cache and hearth_smoother_component_cache.status()
      or { applied = false, active = false }
   result.restock_cleanup = hearth_smoother_restock_guard and hearth_smoother_restock_guard.status()
      or { applied = false, enabled = false, active = false }
   result.function_timing = hearth_smoother_function_timing and hearth_smoother_function_timing.status()
      or { active = false }
   result.timer_dispatch = hearth_smoother_timer_dispatch and hearth_smoother_timer_dispatch.status()
      or { applied = false, enabled = false, active = false }
   result.restock_slice = hearth_smoother_restock_slice and hearth_smoother_restock_slice.status()
      or { applied = false, enabled = false, active = false }
   result.farm_sunlight_slice = hearth_smoother_farm_sunlight_slice and hearth_smoother_farm_sunlight_slice.status()
      or { applied = false, enabled = false, active = false }
   result.restock_bootstrap = hearth_smoother_restock_bootstrap and hearth_smoother_restock_bootstrap.status()
      or { applied = false, enabled = false, active = false }
   return result
end

function M.restore()
   if service then
      merge_back()
      -- Do not overwrite a later patch owned by another mod.
      if service._call_reconsider_callbacks == wrapper then
         service._call_reconsider_callbacks = original
      end
   end
   state.applied = false
   state.empty_dispatch_fast_path = false
   return M.status()
end

function M.apply(ai)
   ai = ai or (stonehearth and stonehearth.ai)
   if state.applied then
      if ai == service and ai._call_reconsider_callbacks == wrapper then return true end
      return false, 'dispatcher was changed by another mod or AI service was replaced'
   end
   if not config.enabled then return false, 'disabled' end
   if not ai or type(ai._call_reconsider_callbacks) ~= 'function'
      or type(ai._reconsidered_entities) ~= 'table'
      or type(ai._reconsider_callbacks) ~= 'table'
      or type(ai._single_entity_reconsider_callbacks) ~= 'table'
      or type(radiant.get_realtime) ~= 'function' then
      return false, 'unsupported AI service layout'
   end
   local clock_ok, time = pcall(now)
   if not clock_ok or type(time) ~= 'number' then return false, 'realtime clock is not ready' end
   service, original = ai, ai._call_reconsider_callbacks
   trusted_callbacks, trusted_registration = ai._reconsider_callbacks, ai.on_reconsider_entity
   -- Stock registration creates plain records. Validate existing entries once;
   -- direct private entry-metatable mutation by other mods is outside this contract.
   state.empty_dispatch_fast_path = has_stock_source(original)
      and has_stock_source(trusted_registration)
      and plain_entries(ai._reconsider_callbacks)
      and plain_entries(ai._single_entity_reconsider_callbacks)
   local captured_original = original
   local this_wrapper
   this_wrapper = function(self)
      if not state.applied or not config.enabled or wrapper ~= this_wrapper then
         return captured_original(self)
      end
      -- Only preparation is protected. Never rerun a partially executed original dispatcher.
      local ok, result = pcall(prepare_batch, self)
      if not ok then
         state.error_count = state.error_count + 1
         state.last_error = tostring(result)
         config.enabled = false
         M.restore()
         pcall(write_status, 'fail-open: ' .. state.last_error)
         return captured_original(self)
      end
      state.active_batch = nil
      if result and owns_empty_fast_path(self) and next(self._reconsidered_entities) == nil then
         local empty = self._reconsidered_entities
         self._reconsidered_entities = {}
         state.empty_fast_calls = state.empty_fast_calls + 1
         -- Exact stock empty side effect; native errors and generated messages propagate.
         _radiant.sim.reconsider_entities(empty)
         return
      end
      -- The original snapshots callbacks, resets its map, runs radiant.xpcall and C++.
      -- Any messages produced during those callbacks stay in the fresh engine map.
      return captured_original(self)
   end
   wrapper = this_wrapper
   ai._call_reconsider_callbacks = wrapper
   state.applied = true
   state.last_log = time
   pcall(write_status, 'applied')
   return true
end

function M.configure(options)
   if type(options) ~= 'table' then return false, 'configuration must be a table' end
   for key, value in pairs(options) do
      if key == 'enabled' then
         if type(value) ~= 'boolean' then return false, 'enabled must be boolean' end
      elseif key == 'batch_size' then
         if type(value) ~= 'number' or value ~= math.floor(value) or value < 16 or value > 256 then
            return false, 'batch_size must be an integer between 16 and 256'
         end
      elseif key == 'max_delay_seconds' then
         if type(value) ~= 'number' or value ~= value or value < 0.1 or value > 1.0 then
            return false, 'max_delay_seconds must be between 0.1 and 1.0'
         end
      else
         return false, 'unsupported configuration key: ' .. tostring(key)
      end
   end
   for key, value in pairs(options) do config[key] = value end
   if not config.enabled then
      M.restore()
   else
      local ok, err = M.apply()
      if not ok then return false, err end
   end
   pcall(write_status, 'configured')
   return true, M.status()
end

return M

